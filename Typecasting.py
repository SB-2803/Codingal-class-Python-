# Assigning Different Variables
name= "Penguin"
age = 15
is_student = True
weight = 38.5

# Printing Different Variables and their Datatypes
print("Name :", name)
print("Data Type of Name is :", type(name))

print("Age :", age)
print("Data Type of Age is :", type(age))

print("Weight :", weight)
print("Data Type of Weight is :", type(weight))

print("Is_student :", is_student)
print("Data Type of Name is :", type(is_student))

# Type casting to convert the datatype of variables
print("\n After Type casting...")
age = str(age)
print(age)
print("Data Type of age is :", type(age))

weight = int(weight)
print(weight)
print("Data Type of weight is :", type(weight))

age = float(age)
print(age)
print("Data Type of Age is :", type(age))