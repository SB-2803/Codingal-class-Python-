import math #importing module 
#using ceil and floor function of the math module
print("The Floor and Ceiling value of 23.56 are:",math.ceil(23.56),",",math.floor(23.56))
x = 10
y = -15
#using copysign function
print("The value of x after copying the sign from y is:",math.copysign(x,y))
#using fabs and gcd function
print("The absolute value of -96 and 56 are:",math.fabs(-96),",",math.fabs(56))
print("The GCD or HCF of 24 and 56 is:",math.gcd(24,56))
#using square root 
print("The square root of 81 is:",math.sqrt(81))